export type JKey = keyof typeof fr;

/** Traduction hors composant (notifications, rapports). */
export function makeTT(language: 'fr' | 'en') {
  return (key: JKey, vars?: Record<string, string | number>) => {
    let s = (language === 'en' ? en : fr)[key] ?? key;
    if (vars) s = s.replace(/\{\{(\w+)\}\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
    return s;
  };
}

export function useJT() {
  const { language } = useLanguage();
  const tt = useCallback(
    (key: JKey, vars?: Record<string, string | number>) => {
      let s = (language === 'en' ? en : fr)[key] ?? key;
      if (vars) s = s.replace(/\{\{(\w+)\}\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
      return s;
    },
    [language],
  );
  return { tt, language, lang: language };
}

