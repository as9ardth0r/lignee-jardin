/**
 * Champignons cultivables (comestibles et médicinaux) : conditions de
 * culture, substrats, calendrier en extérieur. Valeurs de référence des
 * manuels de myciculture (Stamets, guides de culture amateur) ; elles
 * varient selon la souche : suivez d'abord ce qu'indique votre fournisseur.
 */
import type { MonthRange } from '../model';

type T = { fr: string; en: string };

export type MushMethod = 'bag' | 'straw' | 'bucket' | 'log' | 'bed' | 'compost' | 'jar' | 'tree';
export const MUSH_METHODS: MushMethod[] = ['bag', 'straw', 'bucket', 'log', 'bed', 'compost', 'jar', 'tree'];

export type SubstrateId = 'straw' | 'sawdustSupp' | 'masters' | 'pellets' | 'coffee' | 'cardboard' | 'logs' | 'chips' | 'compost' | 'rice' | 'leaves';

export interface MushroomSpecies {
  id: string;
  name: T;
  latin: string;
  emoji: string;
  /** 1 = débutant, 2 = intermédiaire, 3 = avancé. */
  difficulty: 1 | 2 | 3;
  methods: MushMethod[];
  substrates: SubstrateId[];
  /** Température d'incubation (colonisation), °C. */
  colonTemp: [number, number];
  /** Température de fructification, °C. */
  fruitTemp: [number, number];
  /** Un choc froid (ou trempage à l'eau froide) déclenche la fructification. */
  coldShock?: boolean;
  /** Colonisation du substrat en intérieur, jours (à bonne température). */
  colonDays: [number, number];
  /** Du déclenchement aux primordia, jours. */
  pinDays: [number, number];
  /** Des primordia à la récolte, jours. */
  fruitDays: [number, number];
  /** Volées habituelles et repos entre deux volées (jours). */
  flushes: number;
  restDays: number;
  /** Efficacité biologique : g de champignons frais pour 100 g de substrat sec. */
  be: [number, number];
  /** Humidité de l'air pendant la fructification, %. */
  humidity: [number, number];
  /** Besoin d'air frais (sensibilité au CO₂). */
  fae: 'high' | 'medium' | 'low';
  light: 'none' | 'low' | 'medium';
  /** Culture en extérieur : mois d'ensemencement et de récolte, délai avant la 1re récolte (mois), durée de production (ans). */
  outdoor?: { inoculate: MonthRange[]; fruit: MonthRange[]; firstMonths: [number, number]; years: number };
  /** Essences de bois pour les bûches. */
  woods?: T;
  harvest: T;
  note: T;
  caution?: T;
  /** Conservation au réfrigérateur, jours. */
  keepDays: number;
  /** Usage médicinal plutôt que culinaire. */
  medicinal?: boolean;
}

