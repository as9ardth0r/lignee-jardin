export type TomatoKey = keyof typeof fr;

export function useTomatoT() {
  const { language } = useLanguage();
  const tt = useCallback(
    (key: TomatoKey, vars?: Record<string, string | number>) => {
      let s = (language === 'en' ? en : fr)[key] ?? key;
      if (vars) s = s.replace(/\{\{(\w+)\}\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
      return s;
    },
    [language]
  );
  return { tt, language };
}
