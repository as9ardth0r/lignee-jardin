export type SquashKey = keyof typeof fr;

export function useSquashT() {
  const { language } = useLanguage();
  const tt = useCallback(
    (key: SquashKey, vars?: Record<string, string | number>) => {
      let s = (language === 'en' ? en : fr)[key] ?? key;
      if (vars) s = s.replace(/\{\{(\w+)\}\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
      return s;
    },
    [language]
  );
  return { tt, language };
}

export type TT = ReturnType<typeof useSquashT>['tt'];
